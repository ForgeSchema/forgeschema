// Package plan builds deterministic, reviewable PostgreSQL migration plans.
// It does not connect to databases or execute SQL.
package plan

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"github.com/ForgeSchema/forgeschema/internal/strictyaml"
	"github.com/ForgeSchema/forgeschema/schema"
)

const FormatVersion = 1

// Rename identifies a column rename on an existing table. Chains, swaps and
// reuse of the source name in the target are deliberately unsupported.
type Rename struct {
	Table string `yaml:"table" json:"table"`
	From  string `yaml:"from" json:"from"`
	To    string `yaml:"to" json:"to"`
}
type RenameFile struct {
	Version int      `yaml:"version" json:"version"`
	Columns []Rename `yaml:"columns" json:"columns"`
}
type Operation struct {
	Kind        string `json:"kind"`
	Table       string `json:"table"`
	Subject     string `json:"subject,omitempty"`
	SQL         string `json:"sql"`
	Explanation string `json:"explanation"`
}
type Blocker struct {
	Object string `json:"object"`
	Reason string `json:"reason"`
}
type Plan struct {
	FormatVersion     int             `json:"format_version"`
	Source            schema.Document `json:"source"`
	Target            schema.Document `json:"target"`
	SourceFingerprint string          `json:"source_fingerprint"`
	TargetFingerprint string          `json:"target_fingerprint"`
	Renames           []Rename        `json:"renames"`
	Status            string          `json:"status"`
	Operations        []Operation     `json:"operations"`
	Blocked           []Blocker       `json:"blocked"`
	// Online builds indexes on existing tables with CREATE INDEX
	// CONCURRENTLY, outside the migration transaction. Omitted when false, so
	// plans without it keep their 0.1/0.2 JSON and plan ID.
	Online bool `json:"online,omitempty"`
}

// Options select how Build plans supported changes.
type Options struct {
	// Online builds new indexes and unique constraints on existing tables
	// concurrently: see APPLY.md for the three phases this gives apply.
	Online bool
}

// Operation kinds that apply runs outside a transaction.
const ConcurrentIndex = "create_index_concurrently"

func LoadRenames(r io.Reader) ([]Rename, error) {
	var f RenameFile
	if err := strictyaml.Decode(r, &f); err != nil {
		return nil, err
	}
	if f.Version != 1 {
		return nil, fmt.Errorf("rename version must be 1")
	}
	if f.Columns == nil {
		return nil, fmt.Errorf("rename columns is required (use [] for no renames)")
	}
	return f.Columns, nil
}
func quote(s string) string        { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
func qualified(s, t string) string { return quote(s) + "." + quote(t) }
func names(ns []string) string {
	out := make([]string, len(ns))
	for i, n := range ns {
		out[i] = quote(n)
	}
	return strings.Join(out, ", ")
}
func tables(d schema.Document) map[string]schema.Table {
	m := map[string]schema.Table{}
	for _, t := range d.Tables {
		m[t.Name] = t
	}
	return m
}
func columns(t schema.Table) map[string]schema.Column {
	m := map[string]schema.Column{}
	for _, c := range t.Columns {
		m[c.Name] = c
	}
	return m
}
func indexes(t schema.Table) map[string]schema.Index {
	m := map[string]schema.Index{}
	for _, x := range t.Indexes {
		m[x.Name] = x
	}
	return m
}
func uniques(t schema.Table) map[string]schema.Unique {
	m := map[string]schema.Unique{}
	for _, x := range t.Unique {
		m[x.Name] = x
	}
	return m
}
func foreignKeys(t schema.Table) map[string]schema.ForeignKey {
	m := map[string]schema.ForeignKey{}
	for _, x := range t.ForeignKeys {
		m[x.Name] = x
	}
	return m
}
func sameNames(a, b []string) bool { return strings.Join(a, "\x00") == strings.Join(b, "\x00") }

// ColumnSQL renders a column definition for CREATE TABLE or ADD COLUMN.
func ColumnSQL(c schema.Column) string {
	s := quote(c.Name) + " " + c.Type
	switch c.Identity {
	case "always":
		s += " GENERATED ALWAYS AS IDENTITY"
	case "by_default":
		s += " GENERATED BY DEFAULT AS IDENTITY"
	}
	if c.Default != "" {
		s += " DEFAULT " + schema.DefaultSQL(c.Default)
	}
	if c.Nullable {
		return s + " NULL"
	}
	return s + " NOT NULL"
}

// typeModifier extracts the integer arguments of a parameterized type.
func typeModifier(t, base string) ([]int, bool) {
	if !strings.HasPrefix(t, base+"(") {
		return nil, false
	}
	var out []int
	for _, part := range strings.Split(strings.TrimSuffix(strings.TrimPrefix(t, base+"("), ")"), ",") {
		n, err := strconv.Atoi(part)
		if err != nil {
			return nil, false
		}
		out = append(out, n)
	}
	return out, true
}

// widening reports type changes PostgreSQL performs without rewriting the
// table: longer or unbounded varchar, varchar to text and numeric precision
// growth at the same scale.
func widening(from, to string) bool {
	const vc = "character varying"
	if from == vc && to == "text" {
		return true
	}
	if n, ok := typeModifier(from, vc); ok {
		if to == vc || to == "text" {
			return true
		}
		if m, ok := typeModifier(to, vc); ok && m[0] > n[0] {
			return true
		}
	}
	if n, ok := typeModifier(from, "numeric"); ok {
		if to == "numeric" {
			return true
		}
		if m, ok := typeModifier(to, "numeric"); ok && m[0] > n[0] && m[1] == n[1] {
			return true
		}
	}
	return false
}

// Build validates and normalizes both schemas. A blocked plan contains NO
// operations, even if some requested changes would be supported in isolation.
func Build(source, target schema.Document, renames []Rename) (Plan, error) {
	return BuildWith(source, target, renames, Options{})
}

// BuildWith is Build with options.
func BuildWith(source, target schema.Document, renames []Rename, opts Options) (Plan, error) {
	var p Plan
	src, err := schema.Normalize(source)
	if err != nil {
		return p, fmt.Errorf("source: %w", err)
	}
	dst, err := schema.Normalize(target)
	if err != nil {
		return p, fmt.Errorf("target: %w", err)
	}
	if src.Schema != dst.Schema {
		return p, fmt.Errorf("source and target must name the same existing schema")
	}
	hints := append([]Rename{}, renames...)
	sort.Slice(hints, func(i, j int) bool {
		a, b := hints[i], hints[j]
		if a.Table != b.Table {
			return a.Table < b.Table
		}
		if a.From != b.From {
			return a.From < b.From
		}
		return a.To < b.To
	})
	working, err := schema.Normalize(src)
	if err != nil {
		return p, err
	}
	sm, tm := tables(src), tables(dst)
	seenFrom, seenTo := map[string]bool{}, map[string]bool{}
	for _, r := range hints {
		st, ok := sm[r.Table]
		tt, targetOK := tm[r.Table]
		if !ok || !targetOK {
			return p, fmt.Errorf("rename table %q must exist in both source and target", r.Table)
		}
		sc, tc := columns(st), columns(tt)
		_, fromOK := sc[r.From]
		_, toOK := tc[r.To]
		_, occupied := sc[r.To]
		_, reused := tc[r.From]
		if r.From == r.To || !fromOK || !toOK || occupied || reused {
			return p, fmt.Errorf("rename %s.%s to %s: source must exist, target must be new, and old name must not be reused", r.Table, r.From, r.To)
		}
		fromKey, toKey := r.Table+"."+r.From, r.Table+"."+r.To
		if seenFrom[fromKey] || seenTo[toKey] {
			return p, fmt.Errorf("rename mappings must be one-to-one: %s", r.Table)
		}
		seenFrom[fromKey] = true
		seenTo[toKey] = true
	}
	// Apply explicit identities to a separate comparison copy. PostgreSQL adjusts
	// existing key, constraint, index and foreign key references when a column
	// is renamed, including references held by other tables.
	mappings := map[string]map[string]string{}
	for _, r := range hints {
		if mappings[r.Table] == nil {
			mappings[r.Table] = map[string]string{}
		}
		mappings[r.Table][r.From] = r.To
	}
	remap := func(table string, ns []string) {
		for i, n := range ns {
			if next, ok := mappings[table][n]; ok {
				ns[i] = next
			}
		}
	}
	for ti := range working.Tables {
		t := &working.Tables[ti]
		for ci := range t.Columns {
			if n, ok := mappings[t.Name][t.Columns[ci].Name]; ok {
				t.Columns[ci].Name = n
			}
		}
		remap(t.Name, t.PrimaryKey)
		for i := range t.Unique {
			remap(t.Name, t.Unique[i].Columns)
		}
		for i := range t.Indexes {
			remap(t.Name, t.Indexes[i].Columns)
		}
		for i := range t.ForeignKeys {
			remap(t.Name, t.ForeignKeys[i].Columns)
			remap(t.ForeignKeys[i].References.Table, t.ForeignKeys[i].References.Columns)
		}
	}
	wm := tables(working)
	p = Plan{FormatVersion: FormatVersion, Source: src, Target: dst, Renames: hints, Status: "ready", Operations: []Operation{}, Blocked: []Blocker{}, Online: opts.Online}
	if p.SourceFingerprint, err = src.Fingerprint(); err != nil {
		return Plan{}, err
	}
	if p.TargetFingerprint, err = dst.Fingerprint(); err != nil {
		return Plan{}, err
	}
	var createOps, renameOps, addOps, alterOps, indexOps, concurrentOps, attachOps, foreignKeyOps []Operation
	block := func(object, reason string) { p.Blocked = append(p.Blocked, Blocker{object, reason}) }
	alter := func(table string) string { return "ALTER TABLE " + qualified(dst.Schema, table) }
	for _, r := range hints {
		if columns(sm[r.Table])[r.From].Identity != "" {
			block(r.Table+"."+r.From, "renaming an identity column is unsupported; PostgreSQL keeps the old identity sequence name")
		}
	}
	for _, st := range working.Tables {
		if _, ok := tm[st.Name]; !ok {
			block(st.Name, "dropping or implicitly renaming a table is unsupported")
		}
	}
	addForeignKeys := func(tt schema.Table, existing map[string]schema.ForeignKey, created bool) {
		for _, fk := range tt.ForeignKeys {
			if _, ok := existing[fk.Name]; ok {
				continue
			}
			sql := alter(tt.Name) + " ADD CONSTRAINT " + quote(fk.Name) + " FOREIGN KEY (" + names(fk.Columns) + ") REFERENCES " + qualified(dst.Schema, fk.References.Table) + " (" + names(fk.References.Columns) + ")"
			if fk.OnDelete != "" {
				sql += " ON DELETE " + schema.ActionSQL(fk.OnDelete)
			}
			if fk.OnUpdate != "" {
				sql += " ON UPDATE " + schema.ActionSQL(fk.OnUpdate)
			}
			explanation := "Add a foreign key after all tables exist. The new table is empty, so validation is immediate."
			if !created {
				explanation = "Add a foreign key to an existing table. PostgreSQL checks every existing row while blocking writes to this table and " + fk.References.Table + "; the migration fails and rolls back if any row has no match."
			}
			foreignKeyOps = append(foreignKeyOps, Operation{Kind: "add_foreign_key", Table: tt.Name, Subject: fk.Name, SQL: sql + ";", Explanation: explanation})
		}
	}
	addIndexes := func(tt schema.Table, existing map[string]schema.Index, created bool) {
		for _, idx := range tt.Indexes {
			if _, ok := existing[idx.Name]; ok {
				continue
			}
			if opts.Online && !created {
				kind, explanation := "CREATE INDEX CONCURRENTLY ", "Build an ordinary btree index concurrently, outside the migration transaction: reads and writes on the table continue while it builds."
				if idx.Unique {
					kind, explanation = "CREATE UNIQUE INDEX CONCURRENTLY ", "Build a unique btree index concurrently, outside the migration transaction: reads and writes on the table continue while it builds. If existing rows contain duplicates it fails, leaving an invalid index that a rerun of apply drops and builds again."
				}
				concurrentOps = append(concurrentOps, Operation{Kind: ConcurrentIndex, Table: tt.Name, Subject: idx.Name, SQL: kind + quote(idx.Name) + " ON " + qualified(dst.Schema, tt.Name) + " (" + names(idx.Columns) + ");", Explanation: explanation})
				continue
			}
			kind, explanation := "CREATE INDEX ", "Create an ordinary btree index after table and column changes. This is not concurrent and can block writes."
			if idx.Unique {
				kind, explanation = "CREATE UNIQUE INDEX ", "Create a unique btree index after table and column changes. This is not concurrent and can block writes; it fails and rolls back if existing rows contain duplicates."
			}
			indexOps = append(indexOps, Operation{Kind: "create_index", Table: tt.Name, Subject: idx.Name, SQL: kind + quote(idx.Name) + " ON " + qualified(dst.Schema, tt.Name) + " (" + names(idx.Columns) + ");", Explanation: explanation})
		}
	}
	for _, tt := range dst.Tables {
		st, exists := wm[tt.Name]
		if !exists {
			definitions := []string{}
			for _, c := range tt.Columns {
				definitions = append(definitions, ColumnSQL(c))
			}
			if len(tt.PrimaryKey) > 0 {
				definitions = append(definitions, "CONSTRAINT "+quote(tt.Name+"_pkey")+" PRIMARY KEY ("+names(tt.PrimaryKey)+")")
			}
			for _, u := range tt.Unique {
				definitions = append(definitions, "CONSTRAINT "+quote(u.Name)+" UNIQUE ("+names(u.Columns)+")")
			}
			// Keep the 0.1 wording for tables 0.1 could plan, so saved plans stay valid.
			explanation := "Create a new table with its declared columns and primary key; indexes follow separately."
			if len(tt.Unique) > 0 || len(tt.ForeignKeys) > 0 {
				explanation = "Create a new table with its declared columns, primary key and unique constraints; indexes and foreign keys follow separately."
			}
			createOps = append(createOps, Operation{Kind: "create_table", Table: tt.Name, SQL: "CREATE TABLE " + qualified(dst.Schema, tt.Name) + " (" + strings.Join(definitions, ", ") + ");", Explanation: explanation})
			addIndexes(tt, nil, true)
			addForeignKeys(tt, nil, true)
			continue
		}
		sc, tc := columns(st), columns(tt)
		for _, c := range st.Columns {
			if _, ok := tc[c.Name]; !ok {
				block(tt.Name+"."+c.Name, "dropping or implicitly renaming a column is unsupported; provide an explicit rename mapping")
			}
		}
		for _, c := range tt.Columns {
			object := tt.Name + "." + c.Name
			old, ok := sc[c.Name]
			if !ok {
				switch {
				case c.Identity != "":
					block(object, "adding an identity column to an existing table rewrites it to number existing rows, which is unsupported")
				case !c.Nullable && c.Default == "":
					block(object, "adding a required column to an existing table needs a staged data migration")
				default:
					explanation := "Add a nullable column without a default; existing rows receive NULL. Requires a table lock."
					if c.Default != "" {
						explanation = "Add a column with default " + c.Default + ". PostgreSQL stores the default once, so existing rows read it without a table rewrite. Requires a table lock."
						if c.Default == "now()" || c.Default == "current_timestamp" || c.Default == "localtimestamp" || c.Default == "current_date" {
							explanation = "Add a column with default " + c.Default + ". Existing rows all receive the value at migration time, stored once without a table rewrite. Requires a table lock."
						}
						if schema.VolatileDefault(c.Default) {
							explanation = "Add a column with default " + c.Default + ". The default is evaluated per row, so PostgreSQL rewrites the whole table under an exclusive lock to fill existing rows."
						}
					}
					addOps = append(addOps, Operation{Kind: "add_column", Table: tt.Name, Subject: c.Name, SQL: alter(tt.Name) + " ADD COLUMN " + ColumnSQL(c) + ";", Explanation: explanation})
				}
				continue
			}
			if old.Identity != c.Identity {
				block(object, "adding, removing or changing an identity is unsupported")
				continue
			}
			if old.Type != c.Type {
				if widening(old.Type, c.Type) {
					alterOps = append(alterOps, Operation{Kind: "alter_column_type", Table: tt.Name, Subject: c.Name, SQL: alter(tt.Name) + " ALTER COLUMN " + quote(c.Name) + " TYPE " + c.Type + ";", Explanation: "Widen " + old.Type + " to " + c.Type + ". The stored values stay valid, so PostgreSQL does not rewrite the table. Requires a table lock."})
				} else {
					block(object, "type conversions are unsupported")
				}
			}
			if old.Nullable && !c.Nullable {
				alterOps = append(alterOps, Operation{Kind: "set_not_null", Table: tt.Name, Subject: c.Name, SQL: alter(tt.Name) + " ALTER COLUMN " + quote(c.Name) + " SET NOT NULL;", Explanation: "Make the column required. PostgreSQL scans the table under an exclusive lock; the migration fails and rolls back if any row holds NULL."})
			}
			if !old.Nullable && c.Nullable {
				alterOps = append(alterOps, Operation{Kind: "drop_not_null", Table: tt.Name, Subject: c.Name, SQL: alter(tt.Name) + " ALTER COLUMN " + quote(c.Name) + " DROP NOT NULL;", Explanation: "Allow NULL in the column. Metadata-only; requires a brief table lock."})
			}
			if old.Default != c.Default {
				if c.Default == "" {
					alterOps = append(alterOps, Operation{Kind: "drop_default", Table: tt.Name, Subject: c.Name, SQL: alter(tt.Name) + " ALTER COLUMN " + quote(c.Name) + " DROP DEFAULT;", Explanation: "Remove the column default. Existing rows keep their values. Metadata-only; requires a brief table lock."})
				} else {
					alterOps = append(alterOps, Operation{Kind: "set_default", Table: tt.Name, Subject: c.Name, SQL: alter(tt.Name) + " ALTER COLUMN " + quote(c.Name) + " SET DEFAULT " + schema.DefaultSQL(c.Default) + ";", Explanation: "Set the default to " + c.Default + " for future inserts. Existing rows keep their values. Metadata-only; requires a brief table lock."})
				}
			}
		}
		if !sameNames(st.PrimaryKey, tt.PrimaryKey) {
			block(tt.Name, "changing an existing table's primary key is unsupported")
		}
		targetUnique := uniques(tt)
		for _, u := range st.Unique {
			want, ok := targetUnique[u.Name]
			if !ok {
				block(tt.Name+" unique "+u.Name, "dropping or renaming a unique constraint is unsupported")
			} else if !sameNames(u.Columns, want.Columns) {
				block(tt.Name+" unique "+u.Name, "changing a unique constraint is unsupported")
			}
		}
		sourceUnique := uniques(st)
		for _, u := range tt.Unique {
			if _, ok := sourceUnique[u.Name]; ok {
				continue
			}
			if opts.Online {
				concurrentOps = append(concurrentOps, Operation{Kind: ConcurrentIndex, Table: tt.Name, Subject: u.Name, SQL: "CREATE UNIQUE INDEX CONCURRENTLY " + quote(u.Name) + " ON " + qualified(dst.Schema, tt.Name) + " (" + names(u.Columns) + ");", Explanation: "Build the unique index for constraint " + u.Name + " concurrently, outside the migration transaction: reads and writes on the table continue while it builds. If existing rows contain duplicates it fails, leaving an invalid index that a rerun of apply drops and builds again."})
				attachOps = append(attachOps, Operation{Kind: "attach_unique", Table: tt.Name, Subject: u.Name, SQL: alter(tt.Name) + " ADD CONSTRAINT " + quote(u.Name) + " UNIQUE USING INDEX " + quote(u.Name) + ";", Explanation: "Turn the concurrently built index into the unique constraint. Metadata-only; requires a brief table lock."})
				continue
			}
			indexOps = append(indexOps, Operation{Kind: "add_unique", Table: tt.Name, Subject: u.Name, SQL: alter(tt.Name) + " ADD CONSTRAINT " + quote(u.Name) + " UNIQUE (" + names(u.Columns) + ");", Explanation: "Add a unique constraint. PostgreSQL builds its index under an exclusive lock; the migration fails and rolls back if existing rows contain duplicates."})
		}
		targetIndexes := indexes(tt)
		for _, idx := range st.Indexes {
			want, ok := targetIndexes[idx.Name]
			if !ok {
				block(tt.Name+" index "+idx.Name, "dropping or renaming an index is unsupported")
			} else if !sameNames(idx.Columns, want.Columns) || idx.Unique != want.Unique {
				block(tt.Name+" index "+idx.Name, "changing an index definition requires rebuilding it, which is unsupported")
			}
		}
		addIndexes(tt, indexes(st), false)
		targetFKs := foreignKeys(tt)
		for _, fk := range st.ForeignKeys {
			want, ok := targetFKs[fk.Name]
			if !ok {
				block(tt.Name+" foreign key "+fk.Name, "dropping or renaming a foreign key is unsupported")
			} else if schema.ForeignKeyDefinition(fk) != schema.ForeignKeyDefinition(want) {
				block(tt.Name+" foreign key "+fk.Name, "changing a foreign key is unsupported")
			}
		}
		addForeignKeys(tt, foreignKeys(st), false)
	}
	for _, r := range hints {
		renameOps = append(renameOps, Operation{Kind: "rename_column", Table: r.Table, Subject: r.From, SQL: alter(r.Table) + " RENAME COLUMN " + quote(r.From) + " TO " + quote(r.To) + ";", Explanation: "Explicitly rename " + r.From + " to " + r.To + "; PostgreSQL retains column data and updates existing key/index references. Requires a table lock."})
	}
	sort.Slice(p.Blocked, func(i, j int) bool {
		a, b := p.Blocked[i], p.Blocked[j]
		if a.Object != b.Object {
			return a.Object < b.Object
		}
		return a.Reason < b.Reason
	})
	if len(p.Blocked) > 0 {
		p.Status = "blocked"
		return p, nil
	}
	// Concurrent builds come after every transactional change they may
	// depend on, and attaching constraints and adding foreign keys after
	// them, so apply can split an online plan into three phases.
	for _, phase := range [][]Operation{createOps, renameOps, addOps, alterOps, indexOps, concurrentOps, attachOps, foreignKeyOps} {
		p.Operations = append(p.Operations, phase...)
	}
	return p, nil
}

func contains(ns []string, n string) bool {
	for _, x := range ns {
		if x == n {
			return true
		}
	}
	return false
}

// LockedTables returns the existing tables a plan changes, plus tables linked
// by a foreign key to a column whose type changes, which apply locks in
// ACCESS EXCLUSIVE mode, and the existing tables referenced by new foreign
// keys, which apply locks in SHARE ROW EXCLUSIVE mode as PostgreSQL itself
// would. Both lists are sorted and disjoint.
func (p Plan) LockedTables() (exclusive, referenced []string) {
	return p.LockedTablesFor(p.Operations)
}

// LockedTablesFor is LockedTables for some of the plan's operations, such as
// one phase of an online plan. Concurrent index builds take no lock that
// apply has to take for them.
func (p Plan) LockedTablesFor(ops []Operation) (exclusive, referenced []string) {
	existing := tables(p.Source)
	target := tables(p.Target)
	ex, ref := map[string]bool{}, map[string]bool{}
	for _, op := range ops {
		if op.Kind == ConcurrentIndex {
			continue
		}
		if _, ok := existing[op.Table]; ok {
			ex[op.Table] = true
		}
		// Changing a column's type rebuilds the foreign keys it takes part
		// in, which takes ACCESS EXCLUSIVE on the tables at both ends.
		if op.Kind == "alter_column_type" {
			for _, t := range p.Target.Tables {
				for _, fk := range t.ForeignKeys {
					linked := (t.Name == op.Table && contains(fk.Columns, op.Subject)) ||
						(fk.References.Table == op.Table && contains(fk.References.Columns, op.Subject))
					if !linked {
						continue
					}
					for _, other := range []string{t.Name, fk.References.Table} {
						if _, ok := existing[other]; ok {
							ex[other] = true
						}
					}
				}
			}
		}
		if op.Kind == "add_foreign_key" {
			fk := foreignKeys(target[op.Table])[op.Subject]
			if _, ok := existing[fk.References.Table]; ok {
				ref[fk.References.Table] = true
			}
		}
	}
	for t := range ex {
		exclusive = append(exclusive, t)
		delete(ref, t)
	}
	for t := range ref {
		referenced = append(referenced, t)
	}
	sort.Strings(exclusive)
	sort.Strings(referenced)
	return exclusive, referenced
}

// Phases splits the operations for apply: the first transaction, the
// concurrent index builds, and the final transaction. A plan without
// concurrent builds has one phase, all in the first transaction.
func (p Plan) Phases() (first, concurrent, final []Operation) {
	i := 0
	for i < len(p.Operations) && p.Operations[i].Kind != ConcurrentIndex {
		i++
	}
	j := i
	for j < len(p.Operations) && p.Operations[j].Kind == ConcurrentIndex {
		j++
	}
	return p.Operations[:i], p.Operations[i:j], p.Operations[j:]
}

// Intermediate returns the schema an online plan expects after its first
// transaction, and after its concurrent builds, before the final one. The
// final phase's foreign keys are not there yet, and constraints still to be
// attached exist as unique indexes after the builds.
func (p Plan) Intermediate() (afterFirst, beforeFinal schema.Document, err error) {
	_, concurrent, final := p.Phases()
	built, attached, fks := map[string]bool{}, map[string]bool{}, map[string]bool{}
	for _, op := range concurrent {
		built[op.Table+"\x00"+op.Subject] = true
	}
	for _, op := range final {
		switch op.Kind {
		case "attach_unique":
			attached[op.Table+"\x00"+op.Subject] = true
		case "add_foreign_key":
			fks[op.Table+"\x00"+op.Subject] = true
		}
	}
	strip := func(keepBuilt bool) (schema.Document, error) {
		d, err := schema.Normalize(p.Target)
		if err != nil {
			return d, err
		}
		for ti := range d.Tables {
			t := &d.Tables[ti]
			var uniques []schema.Unique
			for _, u := range t.Unique {
				if attached[t.Name+"\x00"+u.Name] {
					if keepBuilt {
						t.Indexes = append(t.Indexes, schema.Index{Name: u.Name, Columns: u.Columns, Unique: true})
					}
					continue
				}
				uniques = append(uniques, u)
			}
			t.Unique = uniques
			var idx []schema.Index
			for _, x := range t.Indexes {
				if built[t.Name+"\x00"+x.Name] && !keepBuilt {
					continue
				}
				idx = append(idx, x)
			}
			t.Indexes = idx
			var keys []schema.ForeignKey
			for _, fk := range t.ForeignKeys {
				if !fks[t.Name+"\x00"+fk.Name] {
					keys = append(keys, fk)
				}
			}
			t.ForeignKeys = keys
		}
		return schema.Normalize(d)
	}
	if afterFirst, err = strip(false); err != nil {
		return afterFirst, beforeFinal, err
	}
	beforeFinal, err = strip(true)
	return afterFirst, beforeFinal, err
}

// Validate rebuilds the plan from its canonical schemas and rename intent and
// rejects altered SQL, operations, explanations, status or fingerprints. It is
// an internal consistency check, not a signature or proof the database matches.
func (p Plan) Validate() error {
	rebuilt, err := BuildWith(p.Source, p.Target, p.Renames, Options{Online: p.Online})
	if err != nil {
		return err
	}
	if !reflect.DeepEqual(p, rebuilt) {
		return fmt.Errorf("plan differs from the canonical plan rebuilt from its schemas and rename mappings")
	}
	return nil
}
func (p Plan) JSON() ([]byte, error) {
	if err := p.Validate(); err != nil {
		return nil, err
	}
	return json.MarshalIndent(p, "", "  ")
}

// Summary presents a human-readable review. Blocked plans include reasons and
// deliberately have no SQL or partial operation list.
func (p Plan) Summary() (string, error) {
	if err := p.Validate(); err != nil {
		return "", err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "ForgeSchema plan: %s\nSource: %s\nTarget: %s\n", p.Status, p.SourceFingerprint, p.TargetFingerprint)
	for _, v := range p.Blocked {
		fmt.Fprintf(&b, "Blocked %s: %s\n", v.Object, v.Reason)
	}
	if p.Status == "ready" && len(p.Operations) == 0 {
		fmt.Fprintln(&b, "No schema changes.")
	}
	first, concurrent, final := p.Phases()
	if len(concurrent) > 0 {
		fmt.Fprintf(&b, "Online plan in three phases: %d operations in a first transaction, %d concurrent index builds outside any transaction, then %d in a final transaction that also verifies the target and records history.\n", len(first), len(concurrent), len(final))
	}
	for i, op := range p.Operations {
		fmt.Fprintf(&b, "%d. %s\n%s\n", i+1, op.Explanation, op.SQL)
	}
	if exclusive, referenced := p.LockedTables(); len(exclusive)+len(referenced) > 0 {
		fmt.Fprintf(&b, "Locks: ACCESS EXCLUSIVE on %s", strings.Join(exclusive, ", "))
		if len(exclusive) == 0 {
			fmt.Fprint(&b, "no existing tables")
		}
		if len(referenced) > 0 {
			fmt.Fprintf(&b, "; SHARE ROW EXCLUSIVE on %s", strings.Join(referenced, ", "))
		}
		fmt.Fprintln(&b)
	}
	fmt.Fprintln(&b, "Review only: this planning command does not execute SQL.")
	return b.String(), nil
}
